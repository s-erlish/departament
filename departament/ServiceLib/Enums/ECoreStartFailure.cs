namespace ServiceLib.Enums;

/// <summary>
/// Чем именно кончилась попытка поднять ядро. Нужен интерфейсу: красный щит без причины — не
/// сообщение, а по одному лишь тексту ошибки причину не отличить (текст ядра приходит на английском
/// и меняется от версии к версии). Структурные случаи <see cref="CoreManager"/> знает точно и
/// называет здесь; <see cref="CoreOutput"/> означает «дальше смотри текст, его напечатало само ядро».
/// </summary>
public enum ECoreStartFailure
{
    /// <summary>Отказа нет: последняя попытка удалась либо ещё не было ни одной.</summary>
    None = 0,

    /// <summary>Нечего запускать: сервер не выбран или профиль не читается.</summary>
    NoServer,

    /// <summary>Исполняемого файла ядра нет на диске.</summary>
    CoreMissing,

    /// <summary>Конфиг для ядра не собрался (шаблон, маршрутизация, поля узла).</summary>
    ConfigFailed,

    /// <summary>Ядро запустилось и умерло; текст отказа — его собственный вывод.</summary>
    CoreOutput,
}
