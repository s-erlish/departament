package com.v2ray.ang.ui.component

import androidx.annotation.MainThread
import com.v2ray.ang.ui.NoticePolicy

/**
 * ГРАБЛЯ №6 — стык оверлея прогрузки и сборки Главной, написанный явно.
 *
 * README §3: «на 6450 мс оверлей снимается и тем же кадром запускается сборка главной. Снимать
 * оверлей и запускать анимацию надо в одной транзакции — иначе главная мелькнёт целиком». Слой
 * прогрузки принадлежит участку начального экрана ([FlowOverlay]), таблица появления §3 — участку
 * Главной. Между ними нужен ровно один однозначный контракт, и это он.
 *
 * **Что делает Главная** — ставит два колбэка один раз, когда её вьюхи существуют
 * (`onViewCreated` / `onStart`), и снимает их, когда вьюхи уходят (`onDestroyView`):
 *
 * ```kotlin
 * HomeHandoff.onPrime = { parkForAssembly() }   // спрятать/сдвинуть то, что будет появляться
 * HomeHandoff.onAssemble = { playAssembly() }   // проиграть таблицу §3
 * ```
 *
 * **Что делает поток прогрузки** — вызывает [prime] в момент старта потока (пока оверлей уже
 * закрывает экран) и [assemble] РОВНО В ТОМ ЖЕ КАДРЕ, в котором снимает себя из иерархии.
 *
 * Почему [prime] отдельно: если Главная соберётся в обычном виде под оверлеем, то в кадре снятия
 * она уже нарисована целиком — и таблица появления начнёт двигать то, что зритель успел увидеть.
 * Предсборочное состояние выставляется заранее, под непрозрачным слоем, где его никто не видит.
 *
 * Оба колбэка необязательны: пока Главная их не поставила, поток работает и просто ничего не
 * запускает — оверлей уходит, под ним обычная Главная. Ни один из двух участков не ждёт другого,
 * чтобы собраться.
 *
 * Обращаться только с главного потока: это поле, а не шина событий, и синхронизации у него нет.
 */
object HomeHandoff {

    /** Поставить Главную в предсборочное состояние. Ставится участком Главной. */
    var onPrime: (() -> Unit)? = null

    /** Проиграть таблицу появления §3. Ставится участком Главной. */
    var onAssemble: (() -> Unit)? = null

    /**
     * Вызывается потоком прогрузки при старте, когда оверлей уже закрыл экран.
     *
     * Здесь же замолкают уведомления. Полноэкранный слой — это ещё и заявление «сейчас идёт вот
     * это»: всё, что вылезет из-под него, отчитывается о деле, которого пользователь не начинал, и
     * о состоянии, которое через секунду перестанет быть верным. Владелец поймал ровно это —
     * «внизу уведомление появилось "нет подписок для обновления"» посреди входа через Telegram.
     * Правило одно и живёт в [NoticePolicy] (правило 5), а не проверкой на одном экране; этот
     * контракт просто единственное место, которое знает обе границы потока.
     */
    @MainThread
    fun prime() {
        NoticePolicy.enterFlow()
        onPrime?.invoke()
    }

    /**
     * Вызывается потоком прогрузки в кадре снятия оверлея. Не откладывать.
     *
     * Симметрично [prime] возвращает голос уведомлениям. Зовётся на всех трёх выходах — успех,
     * отказ, «назад», — поэтому замолчать навсегда поток не может.
     */
    @MainThread
    fun assemble() {
        NoticePolicy.leaveFlow()
        onAssemble?.invoke()
    }
}
